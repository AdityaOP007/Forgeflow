import fs from 'fs';
import os from 'os';
import path from 'path';
import { describe, it, expect, afterEach } from 'vitest';
import {
  renderTemplate,
  TemplateRenderError,
  MAX_TEMPLATE_FILES,
  MAX_TEMPLATE_FILE_BYTES,
} from '../src/templates/engine.js';
import {
  TEMPLATE_REGISTRY,
  getTemplateEntry,
  isTemplateAvailable,
} from '../src/templates/registry.js';

const tempDirs: string[] = [];

function makeTempTemplateDir(): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'forgeflow-tpl-test-'));
  tempDirs.push(dir);
  return dir;
}

afterEach(() => {
  while (tempDirs.length > 0) {
    const dir = tempDirs.pop()!;
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

describe('Template Registry & Engine — Checkpoint 2B', () => {
  describe('Registry', () => {
    it('marks python-fastapi as available at version 1.0.0 and node-express as unavailable', () => {
      const fastapi = getTemplateEntry('python-fastapi');
      expect(fastapi).toEqual({
        slug: 'python-fastapi',
        directory: 'templates/fastapi-service',
        version: '1.0.0',
        available: true,
      });
      expect(isTemplateAvailable('python-fastapi')).toBe(true);

      const node = getTemplateEntry('node-express');
      expect(node?.available).toBe(false);
      expect(isTemplateAvailable('node-express')).toBe(false);
      expect(isTemplateAvailable('unknown-slug')).toBe(false);
      expect(TEMPLATE_REGISTRY.size).toBe(2);
    });
  });

  describe('Template Engine', () => {
    it('renders python-fastapi with expected 21 files and substituted tokens', () => {
      const files = renderTemplate('python-fastapi', {
        serviceName: 'billing-api',
        description: 'Handles billing invoices.',
        templateVersion: '1.0.0',
      });

      const paths = files.map((f) => f.path);
      expect(paths).toEqual([
        '.dockerignore',
        '.env.example',
        '.github/workflows/ci.yml',
        '.gitignore',
        'Dockerfile',
        'README.md',
        'app/__init__.py',
        'app/config.py',
        'app/database.py',
        'app/main.py',
        'app/models.py',
        'app/schemas.py',
        'compose.yaml',
        'constraints.txt',
        'pyproject.toml',
        'requirements-dev.txt',
        'requirements.txt',
        'tests/__init__.py',
        'tests/conftest.py',
        'tests/test_health.py',
        'tests/test_items.py',
      ]);

      const readme = files.find((f) => f.path === 'README.md')!;
      expect(readme.content).toContain('# billing-api');
      expect(readme.content).toContain('Handles billing invoices.');
      expect(readme.content).toContain('Generated by ForgeFlow (template python-fastapi@1.0.0)');

      const envExample = files.find((f) => f.path === '.env.example')!;
      expect(envExample.content).toContain('POSTGRES_DB=billing_api');
      expect(envExample.content).toContain('SERVICE_NAME=billing-api');
    });

    it('keeps token-like text, quotes, backticks, tabs, fenced code, and newlines only in README.md', () => {
      const trickyDescription =
        'Line 1 with __SERVICE_NAME__ literal\t\n\n\n```python\nx=1;y = [1,2 ,3]\n```\nLine 2 with "quotes", \'single\', and `backticks`   '.padEnd(
          300,
          'z'
        );

      const files = renderTemplate('python-fastapi', {
        serviceName: 'orders-api',
        description: trickyDescription,
        templateVersion: '1.0.0',
      });

      const readme = files.find((f) => f.path === 'README.md')!;
      expect(readme.content).toContain(trickyDescription);

      const nonReadmeFiles = files.filter((f) => f.path !== 'README.md');
      for (const f of nonReadmeFiles) {
        expect(f.content).not.toContain(trickyDescription);
        expect(f.content).not.toContain('Line 1 with');
        expect(f.content).not.toContain('x=1;y = [1,2 ,3]');
        expect(f.content).not.toContain('`backticks`');
      }
    });

    it('isolates HOSTILE-MARKER-123 description to README.md and leaves all other files byte-identical to empty description', () => {
      const withHostile = renderTemplate('python-fastapi', {
        serviceName: 'orders-api',
        description: 'Contains HOSTILE-MARKER-123 inside description',
        templateVersion: '1.0.0',
      });
      const withEmpty = renderTemplate('python-fastapi', {
        serviceName: 'orders-api',
        description: '',
        templateVersion: '1.0.0',
      });

      const hostileReadme = withHostile.find((f) => f.path === 'README.md')!;
      expect(hostileReadme.content).toContain('HOSTILE-MARKER-123');

      const nonReadmeHostile = withHostile.filter((f) => f.path !== 'README.md');
      const nonReadmeEmpty = withEmpty.filter((f) => f.path !== 'README.md');

      expect(nonReadmeHostile.length).toBe(nonReadmeEmpty.length);
      for (const f of nonReadmeHostile) {
        expect(f.content).not.toContain('HOSTILE-MARKER-123');
      }
      expect(nonReadmeHostile).toEqual(nonReadmeEmpty);
    });

    it('rejects invalid service names ("../x", uppercase, spaces, too short) and disallowed control characters in description', () => {
      const invalidNames = ['../x', 'MyService', 'my service', 'ab', '1starts-with-num', 'a/b'];
      for (const badName of invalidNames) {
        expect(() =>
          renderTemplate('python-fastapi', {
            serviceName: badName,
            description: 'valid',
            templateVersion: '1.0.0',
          })
        ).toThrow(TemplateRenderError);
      }

      expect(() =>
        renderTemplate('python-fastapi', {
          serviceName: 'valid-name',
          description: 'has null byte \x00',
          templateVersion: '1.0.0',
        })
      ).toThrow(TemplateRenderError);

      expect(() =>
        renderTemplate('python-fastapi', {
          serviceName: 'valid-name',
          description: 'x'.repeat(301),
          templateVersion: '1.0.0',
        })
      ).toThrow(TemplateRenderError);
    });

    it('detects leftover or unknown tokens', () => {
      const dir = makeTempTemplateDir();
      fs.writeFileSync(path.join(dir, 'app.py.tmpl'), 'NAME = "__UNKNOWN_TOKEN__"\n', 'utf8');

      expect(() =>
        renderTemplate(
          'custom',
          { serviceName: 'my-svc', templateVersion: '1.0.0' },
          { templateDir: dir }
        )
      ).toThrow(/Unknown or leftover template token/);
    });

    it('rejects __SERVICE_DESCRIPTION__ outside README.md.tmpl', () => {
      const dir = makeTempTemplateDir();
      fs.writeFileSync(
        path.join(dir, 'main.py.tmpl'),
        'DESC = "__SERVICE_DESCRIPTION__"\n',
        'utf8'
      );

      expect(() =>
        renderTemplate(
          'custom',
          { serviceName: 'my-svc', description: 'hi', templateVersion: '1.0.0' },
          { templateDir: dir }
        )
      ).toThrow(/__SERVICE_DESCRIPTION__ is only allowed in README.md.tmpl/);
    });

    it('rejects symlinks inside template directory', () => {
      const dir = makeTempTemplateDir();
      const target = path.join(dir, 'real.txt.tmpl');
      fs.writeFileSync(target, 'hello __SERVICE_NAME__\n', 'utf8');
      fs.symlinkSync(target, path.join(dir, 'link.txt.tmpl'));

      expect(() =>
        renderTemplate(
          'custom',
          { serviceName: 'my-svc', templateVersion: '1.0.0' },
          { templateDir: dir }
        )
      ).toThrow(/Symlinks are not allowed/);
    });

    it('rejects files exceeding 256 KB and templates exceeding 100 files', () => {
      const bigDir = makeTempTemplateDir();
      fs.writeFileSync(
        path.join(bigDir, 'big.txt.tmpl'),
        Buffer.alloc(MAX_TEMPLATE_FILE_BYTES + 1, 'a')
      );

      expect(() =>
        renderTemplate(
          'custom',
          { serviceName: 'my-svc', templateVersion: '1.0.0' },
          { templateDir: bigDir }
        )
      ).toThrow(/exceeds maximum size/);

      const manyDir = makeTempTemplateDir();
      for (let i = 0; i <= MAX_TEMPLATE_FILES; i++) {
        fs.writeFileSync(path.join(manyDir, `file-${i}.txt.tmpl`), 'ok\n', 'utf8');
      }

      expect(() =>
        renderTemplate(
          'custom',
          { serviceName: 'my-svc', templateVersion: '1.0.0' },
          { templateDir: manyDir }
        )
      ).toThrow(/exceeds maximum file count/);
    });

    it('rejects files without .tmpl extension and rejects path traversal', () => {
      const nonTmplDir = makeTempTemplateDir();
      fs.writeFileSync(path.join(nonTmplDir, 'plain.txt'), 'hello\n', 'utf8');

      expect(() =>
        renderTemplate(
          'custom',
          { serviceName: 'my-svc', templateVersion: '1.0.0' },
          { templateDir: nonTmplDir }
        )
      ).toThrow(/must end with '\.tmpl'/);
    });

    it('produces deterministic byte-identical output for the same inputs', () => {
      const vars = {
        serviceName: 'deterministic-svc',
        description: 'Same input every time.',
        templateVersion: '1.0.0',
      };
      const first = renderTemplate('python-fastapi', vars);
      const second = renderTemplate('python-fastapi', vars);

      expect(first).toEqual(second);
    });
  });
});
